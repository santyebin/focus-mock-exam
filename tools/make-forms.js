#!/usr/bin/env node
/*
 * Builds data/forms.js: five fixed mock forms (the same questions, in the same order, for every student).
 * Each section follows the real exam's blueprint (via the engine's own plan builder) and spreads difficulty from
 * medium-easy to very hard, so a linear form still separates scores across the range. Forms avoid sharing
 * questions where the bank allows. Run again after adding questions: node tools/make-forms.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..');
const ctx = { console };
ctx.globalThis = ctx;
vm.createContext(ctx);
const load = (rel) => vm.runInContext(fs.readFileSync(path.join(root, rel), 'utf8'), ctx, { filename: rel });
['src/irt.js', 'src/scoring.js', 'src/cat.js'].forEach(load);
fs.readdirSync(path.join(root, 'data')).filter((f) => f.endsWith('.js') && f !== 'forms.js').sort().forEach((f) => load('data/' + f));
const GM = ctx.GM;
const bank = GM.CAT.buildBank(GM.BANK);

const FORMS = 5;
const used = new Set(); // question ids already placed in an earlier form
const forms = [];

for (let f = 1; f <= FORMS; f++) {
  const rng = GM.CAT.mulberry32(1000 + f * 7919);
  const form = { id: 'F' + f, name: 'Mock ' + f, sections: {} };
  ['quant', 'verbal', 'di'].forEach((section) => {
    const plan = GM.CAT.buildPlan(section, rng, 0);
    // difficulty targets for each slot: evenly spread from b = -1.0 to +2.0, then shuffled
    const slots = plan.length;
    const targets = Array.from({ length: slots }, (_, i) => -1.0 + (3.0 * i) / Math.max(1, slots - 1));
    for (let i = targets.length - 1; i > 0; i--) { const j = Math.floor(rng() * (i + 1)); [targets[i], targets[j]] = [targets[j], targets[i]]; }
    const takenHere = new Set();
    const ids = [];
    plan.forEach((slot, si) => {
      const t = targets[si];
      const units = bank.units.filter((u) => u.section === section && u.kind === slot.kind && u.cat === slot.cat && !takenHere.has(u.uid));
      const fresh = units.filter((u) => !u.items.some((it) => used.has(it.id)));
      const pool = fresh.length ? fresh : units;
      const meanB = (u) => (slot.kind === 'set' ? u.items.slice(0, slot.size).reduce((s, it) => s + it.irt.b, 0) / Math.min(slot.size, u.items.length) : u.items[0].irt.b);
      const lengthOk = (u) => slot.cat !== 'RC' || (slot.size >= 4) === (u.length === 'long');
      const ranked = pool.slice().sort((a, b) => (Math.abs(meanB(a) - t) + (lengthOk(a) ? 0 : 0.5)) - (Math.abs(meanB(b) - t) + (lengthOk(b) ? 0 : 0.5)));
      const unit = ranked[0];
      if (!unit) throw new Error('bank too small for form ' + f + ' ' + section + ' ' + slot.cat);
      takenHere.add(unit.uid);
      const qs = slot.kind === 'set' ? unit.items.slice(0, slot.size) : [unit.items[0]];
      qs.forEach((it) => { ids.push(it.id); used.add(it.id); });
    });
    if (ids.length !== GM.SECTIONS[section].n) throw new Error('form ' + f + ' ' + section + ' has ' + ids.length + ' questions');
    form.sections[section] = ids;
  });
  forms.push(form);
}

const out = '/* Generated by tools/make-forms.js — fixed mock forms (same questions for every student). Do not edit by hand. */\n' +
  '(function (root) {\n  const GM = (root.GM = root.GM || {});\n  GM.FORMS = ' + JSON.stringify(forms, null, 2).replace(/\n/g, '\n  ') + ';\n})(typeof window !== \'undefined\' ? window : globalThis);\n';
fs.writeFileSync(path.join(root, 'data', 'forms.js'), out);
const share = forms.map((fm) => Object.values(fm.sections).flat()).reduce((acc, ids, i, all) => acc + ids.filter((id) => all.some((o, j) => j !== i && o.includes(id))).length, 0);
console.log(`Wrote data/forms.js: ${forms.length} forms × 64 questions; ${share} question placements shared with another form.`);
